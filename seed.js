import 'dotenv/config';
import mongoose from 'mongoose';
import Record from './models/record.js';

const generateData = async () => {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('Connected to Database. Clearing old records...');
    await Record.deleteMany({});

    const statuses = ['Active', 'Inactive', 'Pending'];
    const categories = ['Finance', 'Healthcare', 'Technology', 'Retail', 'Energy'];
    const countries = ['USA', 'Germany', 'UK', 'Japan', 'Canada', 'Bangladesh', 'Brazil'];

    const totalRecords = 100000;
    const batchSize = 10000;
    let records = [];

    console.log(`Generating ${totalRecords} records...`);

    for (let i = 1; i <= totalRecords; i++) {
      records.push({
        datasetName: `Enterprise Data Set ${i}`,
        category: categories[Math.floor(Math.random() * categories.length)],
        status: statuses[Math.floor(Math.random() * statuses.length)],
        country: countries[Math.floor(Math.random() * countries.length)],
        revenue: Math.floor(Math.random() * 1000000),
        description: `Autogenerated description for dataset record ${i} containing enterprise metrics.`,
      });

      // Insert in batches of 10,000
      if (i % batchSize === 0) {
        await Record.insertMany(records);
        console.log(`Inserted ${i} records...`);
        records = []; // Clear array for next batch
      }
    }

    console.log('Database seeding completed successfully!');
    process.exit();
  } catch (error) {
    console.error('Error seeding database:', error);
    process.exit(1);
  }
};

generateData();